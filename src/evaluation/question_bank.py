def _is_governed_question(row: dict[str, Any]) -> bool:
    """Return True for questions safe to use in default validated train/eval flows."""
    if row.get("status") != "active":
        return False
    if row.get("validation_status") != "validated":
        return False
    recommended_status = row.get("recommended_status")
    if recommended_status and recommended_status != "active":
        return False
    return True


