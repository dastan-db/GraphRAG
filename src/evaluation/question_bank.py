def build_coverage_rows(
    *,
    corpus: str | None = None,
    include_interaction_types: Iterable[str] | None = None,
) -> list[dict[str, Any]]:
    allowed_types = set(include_interaction_types or ["single_turn", "multi_turn"])
    counts: dict[tuple[str, str], dict[str, Any]] = defaultdict(
        lambda: {"train": 0, "test": 0, "holdout": 0, "total": 0}
    )
    for record in load_question_bank(corpus=corpus):
        if record.get("interaction_type") not in allowed_types:
            continue
        key = (record.get("attorney_category"), record.get("architecture_primary"))
        bucket = record.get("eval_split")
        counts[key]["total"] += 1
        if bucket in SPLIT_BUCKETS:
            counts[key][bucket] += 1
    rows: list[dict[str, Any]] = []
    all_keys = set(counts)
    required_cells = get_required_coverage_cells(corpus)
    all_keys.update(required_cells)
    for attorney_category, architecture_primary in sorted(all_keys):
        data = counts.get(
            (attorney_category, architecture_primary),
            {"train": 0, "test": 0, "holdout": 0, "total": 0},
        )
        policy = (
            "required"
            if (attorney_category, architecture_primary) in required_cells
            else ("optional" if data["total"] else "n/a")
        )
        rows.append(
            {
                "corpus": corpus or "all",
                "attorney_category": attorney_category,
                "architecture_primary": architecture_primary,
                "policy": policy,
                "train": data["train"],
                "test": data["test"],
                "holdout": data["holdout"],
                "total": data["total"],
            }
        )
    return rows


def build_domain_coverage_rows(
    *,
    corpus: str | None = None,
    include_interaction_types: Iterable[str] | None = None,
) -> list[dict[str, Any]]:
    allowed_types = set(include_interaction_types or ["single_turn", "multi_turn"])
    counts: dict[str, dict[str, Any]] = defaultdict(
        lambda: {"train": 0, "test": 0, "holdout": 0, "total": 0}
    )
    for record in load_question_bank(corpus=corpus):
        if record.get("interaction_type") not in allowed_types:
            continue
        key = record.get("domain_primary", "unknown")
        bucket = record.get("eval_split")
        counts[key]["total"] += 1
        if bucket in SPLIT_BUCKETS:
            counts[key][bucket] += 1

    rows: list[dict[str, Any]] = []
    all_domains = set(counts)
    domains = get_domain_categories(corpus)
    if isinstance(domains, dict):
        for group in domains.values():
            all_domains.update(group)
    else:
        all_domains.update(domains)

    for domain_primary in sorted(all_domains):
        data = counts.get(domain_primary, {"train": 0, "test": 0, "holdout": 0, "total": 0})
        rows.append(
            {
                "corpus": corpus or "all",
                "domain_primary": domain_primary,
                "train": data["train"],
                "test": data["test"],
                "holdout": data["holdout"],
                "total": data["total"],
            }
        )
    return rows


def build_coverage_matrix(*, corpus: str | None = None):
    import pandas as pd

    return pd.DataFrame(build_coverage_rows(corpus=corpus))


def _stable_split(question_id: str) -> str:
    bucket = int(hashlib.sha1(question_id.encode("utf-8")).hexdigest()[:8], 16) % 100
    if bucket < 60:
        return "train"
    if bucket < 80:
        return "test"
    return "holdout"


def _attorney_from_generated(question: dict[str, Any]) -> str:
    category = (question.get("category") or "").lower()
    primitive = (question.get("primitive") or "").lower()
    if category in {"evidence"}:
        return "documentary_evidence"
    if category in {"cross_reference"}:
        return "corroboration_challenge"
    if category in {"temporal"} or primitive == "timeline":
        return "timeline_reconstruction"
    if category in {"relationship"} or primitive == "entity_pair":
        return "relationship_analysis"
    if category in {"entity_lookup"} or primitive in {"entity_structure", "entity_explore"}:
        return "person_profile"
    if primitive == "keyword_search":
        return "topic_investigation"
    if primitive == "genie_analytics":
        return "quantitative_analysis"
    return "case_synthesis"


def _architecture_from_generated(question: dict[str, Any]) -> str:
    category = (question.get("category") or "").lower()
    primitive = (question.get("primitive") or "").lower()
    if category in {"evidence"}:
        return "evidence_drilldown"
    if category in {"cross_reference"}:
        return "entity_resolution"
    if primitive == "entity_structure":
        return "org_hierarchy_retrieval"
    if primitive == "entity_explore":
        return "entity_summary_retrieval"
    if primitive == "entity_pair":
        return "relationship_path_retrieval"
    if primitive == "timeline":
        return "timeline_retrieval"
    if primitive == "keyword_search":
        return "topic_keyword_retrieval"
    if primitive == "genie_analytics":
        return "analytics_sql_genie"
    return "synthesis_provenance"


def canonicalize_generated_question(
    question: dict[str, Any],
    *,
    corpus: str,
    source_type: str,
    suite_tag: str,
) -> dict[str, Any]:
    question_text = question.get("question") or question.get("question_text") or ""
    payload = {
        "question": question_text,
        "primitive": question.get("primitive", ""),
        "primary_entity": question.get("primary_entity", ""),
        "secondary_entity": question.get("secondary_entity", ""),
        "suite_tag": suite_tag,
        "source_type": source_type,
    }
    question_id = f"{source_type}-" + hashlib.sha1(
        json.dumps(payload, sort_keys=True, ensure_ascii=False).encode("utf-8")
    ).hexdigest()[:10]
    architecture_primary = question.get("architecture_primary") or _architecture_from_generated(question)
    candidate = {
        **copy.deepcopy(question),
        "question_id": question_id,
        "corpus": corpus,
        "interaction_type": question.get("interaction_type", "single_turn"),
        "status": question.get("status", "candidate"),
        "source_type": source_type,
        "suite_tags": list(dict.fromkeys([*question.get("suite_tags", []), suite_tag])),
        "question_text": question_text,
        "attorney_category": question.get("attorney_category") or _attorney_from_generated(question),
        "architecture_primary": architecture_primary,
        "architecture_secondary": question.get(
            "architecture_secondary",
            ["planner_router"] if architecture_primary == "synthesis_provenance" else ["synthesis_provenance"],
        ),
        "eval_split": question.get("eval_split") or _stable_split(question_id),
    }
    domain_primary, domain_secondary = _infer_domain_assignment(candidate)
    candidate["domain_primary"] = question.get("domain_primary") or domain_primary
    candidate["domain_secondary"] = list(question.get("domain_secondary", domain_secondary))
    candidate["coverage_policy"] = (
        "required"
        if (
            candidate.get("attorney_category"),
            candidate.get("architecture_primary"),
        ) in get_required_coverage_cells(candidate.get("corpus"))
        else "optional"
    )
    return candidate


