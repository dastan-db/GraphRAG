def _contains_any(text: str, keywords: Iterable[str]) -> bool:
    lowered = text.lower()
    return any(keyword in lowered for keyword in keywords)


def _domain_tokens(record: dict[str, Any]) -> str:
    parts = [
        record.get("question_text", ""),
        " ".join(record.get("expected_entities", [])),
        record.get("graph_ground_truth", ""),
        record.get("historical_ground_truth", ""),
        " ".join(record.get("suite_tags", [])),
        str(record.get("legacy_category", "")),
    ]
    return " ".join(part for part in parts if part).lower()


