import json, os

def _case(id, cat, q, ops, tools, triples, paths, rubric_notes, gold, why, baseline_fail, mistakes):
    return {
        "id": id,
        "category": cat,
        "user_question": q,
        "required_graph_operations": ops,
        "expected_tool_calls": tools,
        "expected_evidence_bundle": {"triples": triples, "paths": paths},
        "scoring_rubric": {
            "tool_use_correctness":  {"max": 2, "criteria": rubric_notes[0]},
            "evidence_correctness":  {"max": 3, "criteria": rubric_notes[1]},
            "grounded_answer":       {"max": 3, "criteria": rubric_notes[2]},
            "completeness":          {"max": 2, "criteria": rubric_notes[3]},
        },
        "gold_answer": gold,
        "why_graph_wins": why,
        "failure_modes": {
            "baseline_rag_likely_failure": baseline_fail,
            "common_agent_mistakes": mistakes,
        },
    }

def _tc(fn, **kwargs):
    return {"function": fn, "arguments": kwargs}

def _t(s, p, o, src=None):
    t = {"s": s, "p": p, "o": o}
    if src:
        t["source_id"] = src
    return t

